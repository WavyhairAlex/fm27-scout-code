export const dictionaries: Record<Locale, Record<TranslationKey, string>> = {
  en,
  "zh-CN": zhCN,
};

export const LANGUAGE_OPTIONS: { value: Language; label: string }[] = [
  { value: "system", label: "system" },
  { value: "en", label: "English" },
  { value: "zh-CN", label: "简体中文" },
];

export function resolveLocale(preference: Language, languages?: readonly string[]): Locale {
  if (preference === "zh-CN" || preference === "en") return preference;

  const candidates =
    languages ??
    (typeof navigator !== "undefined"
      ? [...(navigator.languages ?? []), navigator.language].filter(Boolean)
      : []);

  for (const candidate of candidates) {
    const tag = candidate.toLowerCase();
    if (tag.startsWith("zh")) return "zh-CN";
    if (tag.startsWith("en")) return "en";
  }
  return "en";
}

export function isLanguage(value: unknown): value is Language {
  return value === "system" || value === "en" || value === "zh-CN";
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  values?: Record<string, string | number>,
): string {
  let text = dictionaries[locale]?.[key] ?? dictionaries.en[key] ?? key;
  if (values) {
    text = text.replace(/\{(\w+)\}/g, (match, name: string) =>
      values[name] == null ? match : String(values[name]),
    );
  }
  return text;
}

export function formatNumber(value: number, locale: Locale): string {
  return value.toLocaleString(locale === "zh-CN" ? "zh-CN" : "en-US");
}

export function formatRelativeTime(iso: string, locale: Locale): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  const diff = Date.now() - date.getTime();
  const minutes = Math.round(diff / 60_000);
  if (minutes < 1) return translate(locale, "time.justNow");
  if (minutes < 60) return translate(locale, "time.minutesAgo", { count: minutes });
  const hours = Math.round(minutes / 60);
  if (hours < 24) return translate(locale, "time.hoursAgo", { count: hours });
  const days = Math.round(hours / 24);
  return translate(locale, "time.daysAgo", { count: days });
}
